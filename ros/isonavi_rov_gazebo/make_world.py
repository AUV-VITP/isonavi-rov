"""Writes the Gazebo pool world from the arena the python course runs use.

The geometry is simulation/isonavi/pool.py's PoolArena, element by element,
so the world follows ArenaConfig and any random layout. The pool is unlit
apart from the vehicle's own lamps, as the course is.

    python3 make_world.py                      # worlds/pool_course.sdf, reference layout
    python3 make_world.py --layout 7 --out w.sdf
    python3 make_world.py --spawn 15 3 -1.0 --no-sensors --no-tether --out w.sdf
"""

from __future__ import annotations

import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "simulation"))
from isonavi.geometry import Box, Cylinder, Sphere   # noqa: E402
from isonavi.pool import ALBEDO, PoolArena, random_arena   # noqa: E402

WALL_T = 0.10
FLOOR_T = 0.10


def f(v):
    return f"{v + 0.0:.6g}"          # + 0.0 turns -0.0 into 0


def vec(*v):
    return " ".join(f(x) for x in v)


def material(rgb, alpha=1.0):
    c = vec(*rgb, alpha)
    return f"<material><ambient>{c}</ambient><diffuse>{c}</diffuse></material>"


def static(name, pose, geometry, rgb, collide=True):
    col = f'<collision name="c"><geometry>{geometry}</geometry></collision>' if collide else ""
    return (f'    <model name="{name}"><static>true</static><pose>{vec(*pose)}</pose><link name="link">'
            f'<visual name="v"><geometry>{geometry}</geometry>{material(rgb)}</visual>{col}</link></model>')


def box(size):
    return f"<box><size>{vec(*size)}</size></box>"


def cyl(r, length):
    return f"<cylinder><radius>{f(r)}</radius><length>{f(length)}</length></cylinder>"


def world(arena, spawn, sensors=True, tether=True, rtf=1.0):
    c = arena.cfg
    tile = ALBEDO[0]
    x = []
    w = x.append
    w('<?xml version="1.0"?>')
    w("<!-- Generated by ros/isonavi_rov_gazebo/make_world.py from simulation/isonavi/pool.py. Do not edit. -->")
    w('<sdf version="1.11">')
    w('  <world name="pool_course">')
    w('    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size>'
      f"<real_time_factor>{f(rtf)}</real_time_factor></physics>")
    w('    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>')
    w('    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>')
    w('    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>')
    if sensors:
        w('    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">'
          "<render_engine>ogre2</render_engine></plugin>")
        w('    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>')
    # Water below z = 0 and air above it, so a vehicle at the surface stops rising.
    w('    <plugin filename="gz-sim-buoyancy-system" name="gz::sim::systems::Buoyancy">'
      "<graded_buoyancy><default_density>1000</default_density>"
      "<density_change><above_depth>0</above_depth><density>1.2</density></density_change>"
      "</graded_buoyancy><enable>isonavi_rov</enable></plugin>")
    # An unlit pool: no sun, almost no ambient light; the vehicle carries its own.
    w("    <scene><ambient>0.02 0.02 0.025 1</ambient><background>0 0 0 1</background>"
      "<shadows>false</shadows><grid>false</grid></scene>")

    # Floor, sloping from depth_start to depth_end along x, as PoolArena.floor_z.
    slope = (c.depth_end - c.depth_start) / c.length
    th = math.atan(slope)
    zc = -(c.depth_start + c.depth_end) / 2 - FLOOR_T / 2 / math.cos(th)
    w(static("pool_floor", (c.length / 2, 0, zc, 0, th, 0),
             box((c.length / math.cos(th) + 2 * WALL_T, c.width + 2 * WALL_T, FLOOR_T)), tile))
    h = c.depth_end + 0.4
    for name, pose, size in (
            ("wall_start", (-WALL_T / 2, 0, 0.4 - h / 2), (WALL_T, c.width, h)),
            ("wall_end", (c.length + WALL_T / 2, 0, 0.4 - h / 2), (WALL_T, c.width, h)),
            ("wall_left", (c.length / 2, c.width / 2 + WALL_T / 2, 0.4 - h / 2), (c.length, WALL_T, h)),
            ("wall_right", (c.length / 2, -c.width / 2 - WALL_T / 2, 0.4 - h / 2), (c.length, WALL_T, h))):
        w(static(name, pose + (0, 0, 0), box(size), tile))
    w('    <model name="water_surface"><static>true</static><pose>' + vec(c.length / 2, 0, 0, 0, 0, 0) +
      '</pose><link name="link"><visual name="v"><geometry>' + box((c.length, c.width, 0.002)) +
      "</geometry>" + material((0.1, 0.4, 0.6), 0.25) + "</visual></link></model>")

    # Course elements, one for one with the arena's scene.
    for p in arena.scene.primitives:
        rgb = ALBEDO[p.material]
        if isinstance(p, Box):
            w(static(p.name, tuple(p.center) + (0, 0, p.yaw), box(2 * p.half), rgb))
        elif isinstance(p, Cylinder):
            w(static(p.name, ((p.cx, p.cy, (p.z0 + p.z1) / 2, 0, 0, 0)), cyl(arena.cfg.pipe_radius, p.z1 - p.z0),
                     rgb))
        elif isinstance(p, Sphere):
            w(static(p.name, tuple(p.c) + (0, 0, 0), f"<sphere><radius>{f(p.r)}</radius></sphere>", rgb))
            zf = float(arena.floor_z(p.c[0]))
            length = (p.c[2] - p.r) - zf
            w(static(p.name + "_string", (p.c[0], p.c[1], zf + length / 2, 0, 0, 0), cyl(0.002, length),
                     (0.3, 0.3, 0.3), collide=False))

    w("    <include>")
    w("      <uri>model://isonavi_rov</uri>")
    w("      <name>isonavi_rov</name>")
    w(f"      <pose>{vec(*spawn)}</pose>")
    w('      <plugin filename="gz-sim-odometry-publisher-system" name="gz::sim::systems::OdometryPublisher">')
    w("        <odom_publish_frequency>50</odom_publish_frequency>")
    w("        <odom_topic>/model/isonavi_rov/odometry</odom_topic>")
    w("        <robot_base_frame>isonavi_rov::base_link</robot_base_frame>")
    w("        <dimensions>3</dimensions>")
    w("      </plugin>")
    if tether:
        # The python course runs' tether drag, applied every physics step.
        w('      <plugin filename="gz-sim-python-system-loader-system" name="gz::sim::systems::PythonSystemLoader">')
        w("        <module_name>isonavi_rov_gazebo.tether_system</module_name>")
        w("      </plugin>")
    w("    </include>")
    w("  </world>")
    w("</sdf>")
    return "\n".join(x) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--layout", type=int, default=0, help="random_arena seed; 0 is the reference layout")
    ap.add_argument("--spawn", type=float, nargs="+", help="x y z [roll pitch yaw] of the CG")
    ap.add_argument("--no-sensors", action="store_true", help="leave out rendering and the IMU, for physics runs")
    ap.add_argument("--no-tether", action="store_true")
    ap.add_argument("--out", default=os.path.join(HERE, "worlds", "pool_course.sdf"))
    a = ap.parse_args()
    arena = PoolArena(random_arena(a.layout)) if a.layout else PoolArena()
    spawn = list(a.spawn) if a.spawn else [arena.cfg.start[0], arena.cfg.start[1], -0.25]
    spawn += [0.0] * (6 - len(spawn))
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w", newline="\n").write(world(arena, spawn, not a.no_sensors, not a.no_tether))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
